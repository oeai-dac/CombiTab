const DICT: Record<Lang, Dict> = { de, en };
/** Nur für Tests: Zugriff auf die Wörterbücher zur Paritätsprüfung. */
export const dictionaries: Record<Lang, Dict> = DICT;

/** Übersetzt `key` in `lang`, interpoliert `{var}` und fällt sonst auf den Schlüssel zurück. */
export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = DICT[lang]?.[key] ?? DICT.de[key] ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(vars[k]));
  return s;
}

/** Gespeicherte Sprache, sonst aus der Browsersprache (de* → de, sonst en). */
export function getInitialLang(): Lang {
  try { const s = localStorage.getItem(KEY); if (s === "de" || s === "en") return s; } catch { /* egal */ }
  const nav = typeof navigator !== "undefined" ? navigator.language.toLowerCase() : "de";
  return nav.startsWith("de") ? "de" : "en";
}

export function setLang(l: Lang): void {
  try { localStorage.setItem(KEY, l); } catch { /* egal */ }
  document.documentElement.setAttribute("lang", l);
  window.dispatchEvent(new CustomEvent<Lang>(LANG_EVENT, { detail: l }));
}

export function onLangChange(cb: (l: Lang) => void): () => void {
  const h = (e: Event) => cb((e as CustomEvent<Lang>).detail);
  window.addEventListener(LANG_EVENT, h);
  return () => window.removeEventListener(LANG_EVENT, h);
}
